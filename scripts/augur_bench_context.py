"""Build long-context benchmark suites from this repository's own source text.

Each case is one user turn: a prefix of concatenated Rust/CUDA source files (deterministic order)
followed by a fixed English question about that code, sized to a target token count with the
model's tokenizer. The source tree is public, so the suite can be regenerated byte-for-byte.

  python scripts/augur_bench_context.py --tokenizer MODEL/tokenizer.json --out bench/context.json --tokens 8192,32768,65536,131072,262144
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
QUESTION = ('\n\nThe text above is source code from one Rust/CUDA inference engine. Reason carefully in English: '
            'identify how a decode step flows from the HTTP request to the CUDA kernels, name the ownership and '
            'validation rules that keep device memory safe, and point out one concrete risk you see in the code.')
# Room for the chat template and thinking preamble, on top of the generated segment.
TEMPLATE_RESERVE = 512


def sources():
    names = subprocess.run(['git', '-C', str(ROOT), 'ls-files', 'crates', 'tools'], capture_output=True, text=True, check=True).stdout.split()
    for name in sorted(n for n in names if n.endswith(('.rs', '.cu', '.cuh', '.h'))):
        yield name, (ROOT / name).read_text(encoding='utf-8', errors='replace')


def build(tokenizer, budget, output):
    """Largest line prefix of the source text whose prompt fits the context after the output budget."""
    from tokenizers import Tokenizer
    tok = Tokenizer.from_file(str(tokenizer))
    count = lambda text: len(tok.encode(text, add_special_tokens=False).ids)
    room = budget - output - TEMPLATE_RESERVE - count(QUESTION)
    lines = [line for name, text in sources() for line in f'// file: {name}\n{text}\n'.splitlines(keepends=True)]
    # Token counts are near-additive over lines; bisect the line prefix, then confirm the exact count.
    lo, hi = 0, len(lines)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if count(''.join(lines[:mid])) <= room: lo = mid
        else: hi = mid - 1
    prompt = ''.join(lines[:lo]) + QUESTION
    return prompt, count(prompt)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--tokenizer', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--tokens', default='8192,32768,65536,131072,262144', help='context capacities to target')
    p.add_argument('--max-completion-tokens', type=int, default=1024)
    a = p.parse_args()
    cases = []
    for budget in map(int, a.tokens.split(',')):
        prompt, n = build(a.tokenizer, budget, a.max_completion_tokens)
        cases.append(dict(name=f'context_{budget // 1024}k', context_tokens=budget, prompt_tokens_approx=n,
                          prompt_sha256=hashlib.sha256(prompt.encode()).hexdigest(),
                          max_completion_tokens=a.max_completion_tokens, messages=[dict(role='user', content=prompt)]))
        print(cases[-1]['name'], n, flush=True)
    suite = dict(schema='augur-bench-suite-v1', name='repository-context',
                 description='Long English questions over this repository\'s own source code, one per context capacity. '
                             'Measures prefill and decode speed at depth, not answer quality.',
                 request=dict(model='quasar-27b', stream=False, enable_thinking=True, reasoning_effort='xhigh',
                              temperature=1.0, top_p=0.95, top_k=20, min_p=0, presence_penalty=0, frequency_penalty=0, seed=0),
                 cases=cases)
    a.out.write_text(json.dumps(suite, ensure_ascii=False) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
